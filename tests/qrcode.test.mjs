test('QR symbols match Nayuki golden matrices across modes, levels and versions', () => {
  const levels = { LOW: QrEcc.LOW, MEDIUM: QrEcc.MEDIUM, QUARTILE: QrEcc.QUARTILE, HIGH: QrEcc.HIGH };
  for (const item of cases) {
    const qr = QrCode.encodeText(item.text, levels[item.ecl]);
    assert.equal(qr.size, item.size, `${item.text.slice(0, 24)} size`);
    const rows = [];
    for (let y = 0; y < qr.size; y++) {
      let row = '';
      for (let x = 0; x < qr.size; x++) row += qr.getModule(x, y) ? '1' : '0';
      rows.push(row);
    }
    assert.deepEqual(rows, item.rows, `${item.text.slice(0, 24)} matrix`);
  }
});

test('path commands cover every dark module and nothing else', () => {
  const qr = encodeQrText('https://github.com/login/device?user_code=ABCD-EFGH', QrEcc.LOW);
  let dark = 0;
  for (let y = 0; y < qr.size; y++) {
    for (let x = 0; x < qr.size; x++) if (qr.getModule(x, y)) dark++;
  }
  const cell = 4;
  const margin = 4;
  const path = qrPathCommands(qr, cell, margin);
  const limit = (qr.size + margin * 2) * cell;
  const commands = [...path.matchAll(/M (\d+) (\d+) h (\d+) v (\d+) h (-?\d+) z/g)];
  assert.equal(commands.length, dark);
  for (const match of commands) {
    const x = Number(match[1]);
    const y = Number(match[2]);
    assert.ok(Number.isInteger(x) && x >= margin * cell && x < limit - cell);
    assert.ok(Number.isInteger(y) && y >= margin * cell && y < limit - cell);
    assert.equal(Number(match[3]), cell);
    assert.equal(Number(match[4]), cell);
    assert.equal(Number(match[5]), -cell);
  }
  const empty = qrPathCommands(encodeQrText('', QrEcc.LOW), cell, margin);
  assert.ok(empty.startsWith('M 16 16 h 4 v 4 h -4 z'));
  assert.ok(!empty.includes(' M ' + (limit - cell) + ' '));
});
